  if (fwd && tt <= bt) tt = Date.UTC(by, bm, TERM_DAY[bm % 12]);
  if (!fwd && tt > bt) tt = Date.UTC(by, bm - 2, TERM_DAY[(bm + 10) % 12]);
  const start = Math.max(1, Math.round(Math.abs(tt - bt) / 864e5 / 3)), [ty] = todayKST(), age = ty - by;
